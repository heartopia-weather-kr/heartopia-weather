const assert=require('node:assert/strict');
require('../assets/weather-core.js');
require('../assets/weather-visual.js');
const V=globalThis.WeatherVisual;
const start='2026-11-09';
const names=Array(24).fill('Sunny');
names[3]='Cloudy';names[4]='Cloudy';names[9]='Light Rain';names[18]='Clear';names[19]='Cloudy';
const day={startDate:start,weather:names.map((weather,i)=>({time:String(i).padStart(2,'0')+':00',weather}))};
const output=V.shareText(day);
assert.match(output,/11월 9일 \(월\)/);
assert.match(output,/00:00 맑음 \[정기\]/);
assert.match(output,/03:00 흐림/);
assert.match(output,/06:00 맑음 \[정기\]/);
assert.match(output,/09:00 약한 비/);
assert.match(output,/12:00 맑음 \[정기\]/);
assert.match(output,/18:00 쾌청 \[정기\]/);
assert.match(output,/19:00 흐림/);
assert.doesNotMatch(output,/07:00/);
const same={startDate:start,weather:day.weather.map(row=>({...row,weather:'Sunny'}))};
assert.equal(V.shareText(same).split('\n').filter(line=>/\[정기\]/.test(line)).length,4);
const missing=structuredClone(day);missing.weather[5].weather='Unknown';
assert.match(V.shareText(missing),/06:00 맑음 \[정기\]/);
const bad=structuredClone(day);bad.weather.pop();assert.throws(()=>V.shareText(bad));
const wrong=structuredClone(day);wrong.weather[1].time='11:00';assert.throws(()=>V.shareText(wrong));
console.log('PASS: calendar-day regular slots, true changes, unknown weather and invalid data');
