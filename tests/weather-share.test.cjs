const assert=require('node:assert/strict');
require('../assets/weather-core.js');
require('../assets/weather-visual.js');
const V=globalThis.WeatherVisual;
const start='2026-11-09';
const names=Array(24).fill('Sunny');
names[3]='Cloudy';names[4]='Cloudy';names[9]='Light Rain';names[18]='Clear';names[19]='Cloudy';
const day={startDate:start,weather:names.map((weather,i)=>({time:String((i+6)%24).padStart(2,'0')+':00',weather}))};
const output=V.shareText(day);
assert.match(output,/11월 9일 \(월\)/);
assert.match(output,/06:00 맑음 \[정기\]/);
assert.match(output,/09:00 흐림\n/);
assert.match(output,/12:00 맑음 \[정기\]/);
assert.match(output,/15:00 약한 비\n/);
assert.match(output,/18:00 맑음 \[정기\]/);
assert.match(output,/다음 날 00:00 쾌청 \[정기\]/);
assert.match(output,/다음 날 01:00 흐림/);
assert.doesNotMatch(output,/07:00/);
assert.doesNotMatch(output,/\[변경\]/);
const same={startDate:start,weather:day.weather.map(row=>({...row,weather:'Sunny'}))};
assert.equal(V.shareText(same).split('\n').filter(line=>/\[정기\]/.test(line)).length,4);
